import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../server.ts', import.meta.url);
const outputPath = new URL('../server.cloudflare.ts', import.meta.url);

let source = await readFile(sourcePath, 'utf8');

const startMarker = '\nasync function startServer() {';
const startIndex = source.indexOf(startMarker);
if (startIndex < 0) {
  throw new Error('Cloudflare build aborted: server.ts startServer() marker was not found.');
}

source = source.slice(0, startIndex).trimEnd() + '\n';
source = source
  .replace("import path from 'path';\n", '')
  .replace("import { createServer as createViteServer } from 'vite';\n", '')
  .replace('const app = express();', 'export const app = express();');

if (!source.includes('export const app = express();')) {
  throw new Error('Cloudflare build aborted: Express app export could not be generated.');
}
if (/createViteServer|path\.join|app\.listen\(/.test(source)) {
  throw new Error('Cloudflare build aborted: Node bootstrap code leaked into the Worker server entry.');
}

const generated = `// AUTO-GENERATED by scripts/build-cloudflare-server.mjs.\n// Do not edit this file; edit server.ts instead.\n${source}`;
await writeFile(outputPath, generated, 'utf8');
console.log('Generated server.cloudflare.ts from server.ts');
